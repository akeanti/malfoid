#!/usr/bin/env python3
"""Generate the firmware header and the website module from spells/spellbook.json.

    python tools/gen_spellbook.py          # write both outputs
    python tools/gen_spellbook.py --check  # exit 1 if outputs are stale (used in CI)

Shapes are expanded here so that the firmware and the website only ever see plain
polylines: one spell may produce several templates (e.g. a circle drawn from four
different starting points).
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "spells" / "spellbook.json"
HEADER = ROOT / "firmware" / "lib" / "malfoid_core" / "src" / "malfoid" / "spellbook_data.h"
WEB = ROOT / "docs" / "js" / "spellbook.js"

MAX_HAPTICS = 4
BANNER = "AUTO-GENERATED by tools/gen_spellbook.py from spells/spellbook.json - do not edit by hand."


def circle(direction: str, segments: int, start_deg: float) -> list[list[float]]:
    sign = -1.0 if direction == "cw" else 1.0  # y grows upward, so clockwise = decreasing angle
    start = math.radians(start_deg)
    return [
        [math.cos(start + sign * 2 * math.pi * k / segments), math.sin(start + sign * 2 * math.pi * k / segments)]
        for k in range(segments + 1)
    ]


def expand(spell: dict) -> list[list[list[float]]]:
    if "path" in spell:
        return [spell["path"]]
    shape = spell["shape"]
    if "circle" in shape:
        return [circle(shape["circle"], shape.get("segments", 16), s) for s in shape.get("starts", [90])]
    raise ValueError(f"spell {spell['id']!r}: unknown shape {shape!r}")


def load() -> tuple[dict, list[dict]]:
    book = json.loads(SOURCE.read_text(encoding="utf-8"))
    templates = []
    seen = set()
    for index, spell in enumerate(book["spells"]):
        sid = spell["id"]
        if sid in seen or not sid.isidentifier() or len(sid) > 15:
            raise ValueError(f"spell id {sid!r} must be unique, an identifier and at most 15 chars")
        seen.add(sid)
        if len(spell.get("haptics", [])) > MAX_HAPTICS:
            raise ValueError(f"spell {sid!r}: at most {MAX_HAPTICS} haptic effects")
        for path in expand(spell):
            if len(path) < 2:
                raise ValueError(f"spell {sid!r}: a path needs at least two points")
            templates.append({"spell": index, "path": [[round(x, 4), round(y, 4)] for x, y in path]})
    return book, templates


def c_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=True)  # JSON escaping is valid C escaping for our text


def render_header(book: dict, templates: list[dict]) -> str:
    out = [f"// {BANNER}", "#pragma once", "", "#include <cstddef>", "#include <cstdint>", "",
           "namespace malfoid {", "namespace spellbook {", "",
           f"constexpr size_t kPoints = {book['points']};", "",
           "struct SpellInfo {",
           "  const char* id;",
           "  const char* name;",
           "  const char* gesture;",
           "  const char* effect;",
           "  uint32_t rgb;          // 0xRRGGBB",
           f"  uint8_t haptics[{MAX_HAPTICS}];  // DRV2605L ROM effect ids, 0 = end",
           "};", "",
           "struct TemplateDef {",
           "  uint8_t spell;     // index into kSpells",
           "  uint8_t count;     // number of (x, y) pairs",
           "  const float* xy;   // interleaved x0, y0, x1, y1, ...",
           "};", ""]
    out.append("inline constexpr SpellInfo kSpells[] = {")
    for s in book["spells"]:
        haptics = (s.get("haptics", []) + [0] * MAX_HAPTICS)[:MAX_HAPTICS]
        rgb = int(s["color"].lstrip("#"), 16)
        out.append(f"    {{{c_string(s['id'])}, {c_string(s['name'])}, {c_string(s['gesture'])}, "
                   f"{c_string(s['effect'])}, 0x{rgb:06X}, {{{', '.join(map(str, haptics))}}}}},")
    out += ["};", f"constexpr size_t kSpellCount = {len(book['spells'])};", ""]
    for i, t in enumerate(templates):
        flat = ", ".join(f"{v:.4f}f" for point in t["path"] for v in point)
        out.append(f"inline constexpr float kT{i}[] = {{{flat}}};")
    out += ["", "inline constexpr TemplateDef kTemplates[] = {"]
    for i, t in enumerate(templates):
        out.append(f"    {{{t['spell']}, {len(t['path'])}, kT{i}}},")
    out += ["};", f"constexpr size_t kTemplateCount = {len(templates)};", "",
            "}  // namespace spellbook", "}  // namespace malfoid", ""]
    return "\n".join(out)


def render_web(book: dict, templates: list[dict]) -> str:
    spells = [{k: s[k] for k in ("id", "name", "gesture", "effect", "color")} for s in book["spells"]]
    data = {
        "points": book["points"],
        "spells": spells,
        "templates": [{"spell": book["spells"][t["spell"]]["id"], "path": t["path"]} for t in templates],
    }
    return f"// {BANNER}\nexport const SPELLBOOK = {json.dumps(data, indent=2)};\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args()

    book, templates = load()
    outputs = {HEADER: render_header(book, templates), WEB: render_web(book, templates)}
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} - run python tools/gen_spellbook.py", file=sys.stderr)
        return 1 if stale else 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    print(f"{len(book['spells'])} spells, {len(templates)} templates")
    return 0


if __name__ == "__main__":
    sys.exit(main())
